/** An account at a bank abroad, with a real IBAN check (generic mod 97). */
function foreignBankAccount(country) {
  const [bic, name, bank, length] = FOREIGN_BANKS[country];
  const bban = bank + Array.from({ length }, () => between(0, 9)).join('');
  const check = String(98 - mod97(`${bban}${letterDigits(country)}00`)).padStart(2, '0');
  const iban = `${country}${check}${bban}`.replace(/(.{4})/g, '$1 ').trim();

  return { iban, bic, bank_name: name };
}

