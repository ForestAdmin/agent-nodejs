function mod97(digits) {
  return Number(BigInt(digits) % 97n);
}

/** A French IBAN with real check digits (RIB key and IBAN key), at our bank or another one. */
function frenchIban(accountNumber, bankCode = BANK_CODE, branch = '00042') {
  const account = String(accountNumber).padStart(11, '0');
  const key = String(97 - mod97(`${bankCode}${branch}${account}00`)).padStart(2, '0');
  const bban = `${bankCode}${branch}${account}${key}`;
  const check = String(98 - mod97(`${bban}152700`)).padStart(2, '0'); // F=15 R=27

  return `FR${check}${bban}`.replace(/(.{4})/g, '$1 ').trim();
}

